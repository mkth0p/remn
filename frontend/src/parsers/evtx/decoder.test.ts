import { afterEach, expect, it, vi } from 'vitest'
import { DECODER_STOPPED, EvtxDecoder } from './decoder'
import { loadEvtxDecoder } from './load'

// A module with the decoder's exports whose parse_chunk executes `unreachable`, which is how a
// panic ends in a build with panic = "abort". Written by hand for this test; no EVTX input is known
// to make the real decoder panic.
const TRAPS = new Uint8Array([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, 0x01, 0x10, 0x03, 0x60, 0x01, 0x7f, 0x01, 0x7f, 0x60, 0x02, 0x7f, 0x7f, 0x01, 0x7f, 0x60, 0x00, 0x01, 0x7f, 0x03, 0x05, 0x04, 0x00, 0x01, 0x02, 0x02,
  0x05, 0x03, 0x01, 0x00, 0x01, 0x07, 0x34, 0x05, 0x06, 0x6d, 0x65, 0x6d, 0x6f, 0x72, 0x79, 0x02, 0x00, 0x05, 0x61, 0x6c, 0x6c, 0x6f, 0x63, 0x00, 0x00, 0x0b, 0x70, 0x61, 0x72, 0x73, 0x65, 0x5f, 0x63,
  0x68, 0x75, 0x6e, 0x6b, 0x00, 0x01, 0x07, 0x6f, 0x75, 0x74, 0x5f, 0x70, 0x74, 0x72, 0x00, 0x02, 0x07, 0x6f, 0x75, 0x74, 0x5f, 0x6c, 0x65, 0x6e, 0x00, 0x03, 0x0a, 0x14, 0x04, 0x04, 0x00, 0x41, 0x00,
  0x0b, 0x03, 0x00, 0x00, 0x0b, 0x04, 0x00, 0x41, 0x00, 0x0b, 0x04, 0x00, 0x41, 0x00, 0x0b,
])

afterEach(() => vi.unstubAllGlobals())

it('says the file was cut when the decoder traps, as the server says it, and decodes nothing more', async () => {
  const decoder = await EvtxDecoder.load(TRAPS)
  expect(() => decoder.chunk(new Uint8Array(512))).toThrow(DECODER_STOPPED)
  expect(decoder.trapped).toBe(true)
  expect(() => decoder.chunk(new Uint8Array(512))).toThrow(DECODER_STOPPED)
})

it('gives the next file a new instance once one has trapped', async () => {
  const fetches = vi.fn(async () => new Response(TRAPS))
  vi.stubGlobal('fetch', fetches)
  const first = await loadEvtxDecoder()
  expect(await loadEvtxDecoder()).toBe(first)
  expect(() => first.chunk(new Uint8Array(512))).toThrow(DECODER_STOPPED)
  const second = await loadEvtxDecoder()
  expect(second).not.toBe(first)
  expect(second.trapped).toBe(false)
  expect(fetches).toHaveBeenCalledTimes(2)
})
